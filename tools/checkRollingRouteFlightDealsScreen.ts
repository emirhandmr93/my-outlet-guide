import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { supportedLanguageCodes, translations } from "../src/translations/translations";
import { extractUserFacingTextCandidates } from "./userFacingTextAudit";

const screen = readFileSync("src/screens/FlightDealsScreen.tsx", "utf8");
assert.doesNotMatch(screen, /DateTimePicker/);
assert.doesNotMatch(screen, /WebDatePickerButton/);
assert.doesNotMatch(screen, /\[departDate,\s*setDepartDate\]|\[returnDate,\s*setReturnDate\]/);
assert.doesNotMatch(screen, /\[adults,\s*setAdults\]|\[children,\s*setChildren\]|\[infants,\s*setInfants\]/);
assert.doesNotMatch(screen, /CounterButton|counterRow|adjustPassenger/);
assert.match(screen, /submitRollingRouteFlightDealAlert\(\{/);
const submissionCall = screen.slice(screen.indexOf("submitRollingRouteFlightDealAlert({"), screen.indexOf("});", screen.indexOf("submitRollingRouteFlightDealAlert({")) + 3);
for (const field of ["departDate", "returnDate", "adults", "children", "infants"]) assert(!submissionCall.includes(field), `rolling submission forwards ${field}`);
assert.match(screen, /listAllFlightDealAlerts\(currentUser\.uid\)/);
assert.match(screen, /function editAlert\(alert: RollingRouteFlightDealAlertPreference\)/);
assert.match(screen, /alert\.schemaVersion === 3 \? <ActionButton label=\{t\("flightDeals\.editAlert"\)\}/);
assert.doesNotMatch(screen, /schemaVersion === 2[^\n]+editAlert/);
assert.match(screen, /setFlightDealAlertActive/);
assert.match(screen, /deleteFlightDealAlert/);
const rollingCard = screen.slice(screen.indexOf("{alert.schemaVersion === 3 ? ("), screen.indexOf(") : (", screen.indexOf("{alert.schemaVersion === 3 ? (")));
assert.doesNotMatch(rollingCard, /departDate|returnDate|passengerSummary|\.adults|\.children|\.infants/);
assert.match(screen, /flightDeals\.legacyDatedAlert/);
assert.match(screen, /flightDeals\.legacyAlertExplanation/);
assert.match(screen, /trip\.flightDetails\?\.return/);
assert.match(screen, /flightDeals\.tripReminders/);
const keys = ["flightDeals.rollingExplanation", "flightDeals.rollingMonitoringStatus", "flightDeals.legacyDatedAlert", "flightDeals.legacyAlertExplanation", "flightDeals.savedAlertsEmptyRolling", "flightDeals.originRequired", "flightDeals.destinationRequired", "flightDeals.tripTypeError", "flightDeals.tripClassError", "flightDeals.directOnlyError"];
assert.deepEqual([...supportedLanguageCodes].sort(), ["ar", "de", "en", "es", "fr", "ru", "tr", "zh"]);
for (const locale of supportedLanguageCodes) for (const key of keys) assert(translations[locale][key]?.trim(), `${locale} missing ${key}`);
const candidates = extractUserFacingTextCandidates(screen);
assert(!candidates.some(value => /No dates|Legacy dated|Tarih seç|Eski tarihli/.test(value)), "new explanatory copy must use translations");
console.log("Rolling-route Flight Deals screen checks passed.");

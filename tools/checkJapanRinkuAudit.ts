const difference = <T>(left: readonly T[], right: readonly T[]) => [...new Set(left)].filter(value => !new Set(right).has(value));
const unique = <T>(values: T[]) => new Set(values).size === values.length;
const semanticKey = (value: string) => value.normalize("NFKD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]/g, "");

const rinku = outlets.filter(outlet => outlet.outletId === outletId);
assert.equal(rinku.length, 1, "exactly one Rinku outlet record");
assert.equal(rinku[0].status, "active");
assert.equal(rinku[0].countryId, "japan");
assert.equal(rinku[0].cityId, "izumisano");
assert.equal(cities.filter(city => city.cityId === "izumisano" && city.countryId === "japan").length, 1);
assert.ok(unique(brands.map(brand => brand.brandId)), "duplicate global brand IDs");
assert.ok(unique(outletBrands.map(relation => `${relation.outletId}:${relation.brandId}`)), "duplicate outlet-brand relationship");
assert.ok(unique(restaurants.map(restaurant => restaurant.restaurantId)), "duplicate restaurant IDs");
for (const relation of outletBrands.filter(relation => relation.outletId === outletId)) {
  assert.equal(brands.filter(brand => brand.brandId === relation.brandId).length, 1, `Rinku brand does not resolve exactly once: ${relation.brandId}`);
}
for (const brandId of newlyCreatedBrandIds) {
  const brand = brands.find(candidate => candidate.brandId === brandId);
  assert.ok(brand, `new brand missing: ${brandId}`);
  const keys = new Set([brand.brandName, ...(brand.aliases ?? [])].map(semanticKey));
  const collisions = brands.filter(candidate => candidate.brandId !== brandId && [candidate.brandName, ...(candidate.aliases ?? [])].some(name => keys.has(semanticKey(name))));
  assert.deepEqual(collisions.map(candidate => candidate.brandId), [], `semantic duplicate for ${brandId}`);
}
